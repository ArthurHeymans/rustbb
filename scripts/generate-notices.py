#!/usr/bin/env python3
"""Generate an embedded license/source-availability bundle from locked metadata."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def generate():
    try:
        metadata = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version=1", "--locked", "--all-features"], cwd=ROOT))
    except (ValueError, OSError, subprocess.SubprocessError) as error:
        raise RuntimeError("could not read locked Cargo metadata") from error
    lock = tomllib.loads((ROOT / "Cargo.lock").read_text())
    checksums = {(p["name"], p["version"]): p.get("checksum", "local source") for p in lock["package"]}
    output = ["Rust initramfs third-party licenses and source availability\n",
              "Generated by scripts/generate-notices.py from Cargo.lock.\n",
              "This is a superset of workspace dependencies; not every listed package is linked into every image.\n",
              "Our separate source files are MIT OR Apache-2.0. Dependencies keep their own licenses.\n",
              "MPL-covered source and any distributed modifications remain MPL-2.0; linking does not relicense our separate files.\n\n"]
    seen = {}
    packages = sorted(metadata["packages"], key=lambda p: (p["name"], p["version"]))
    for package in packages:
        directory = Path(package["manifest_path"]).parent
        if package["source"] is None and not directory.is_relative_to(ROOT / "vendor"):
            continue
        name, version = package["name"], package["version"]
        output += [f"\n{'=' * 72}\n{name} {version}\nLicense: {package.get('license') or 'see license file'}\n",
                   f"Source archive: https://crates.io/api/v1/crates/{name}/{version}/download\n",
                   f"Archive SHA-256: {checksums.get((name, version), 'see vendor provenance')}\n"]
        if package.get("repository"):
            output.append(f"Upstream: {package['repository']}\n")
        if directory.is_relative_to(ROOT / "vendor"):
            output.append("Locally patched source: vendor/ in the corresponding rustbb source tree. See RBB_PATCHES.md for provenance and changes.\n")
        files = [p for p in directory.iterdir() if p.is_file() and p.name.upper().startswith(("LICENSE", "COPYING", "NOTICE", "COPYRIGHT", "UNLICENSE"))]
        if package.get("license_file"):
            files.append(directory / package["license_file"])
        for path in sorted(set(files)):
            if not path.resolve().is_relative_to(directory.resolve()):
                raise RuntimeError(f"license path escapes crate: {path}")
            if path.stat().st_size > 1024 * 1024:
                raise RuntimeError(f"license file too large: {path}")
            text = path.read_text(errors="replace")
            checksum = hashlib.sha256(text.encode()).hexdigest()
            output.append(f"\n--- {path.name} (SHA-256 {checksum}) ---\n")
            if checksum in seen:
                output.append(f"Identical full text is included above under {seen[checksum]}.\n")
            else:
                seen[checksum] = f"{name} {version}: {path.name}"
                output.extend([text, "\n"])
        if name == "boot-loader-spec":
            # This crate's published archive has no top-level LICENSE file;
            # preserve the source header and explicit MPL/source availability.
            output += ["\nCopyright 2022 Alberto Ruiz <aruiz@gnome.org>\n",
                       "This Source Code Form is subject to the Mozilla Public License, v. 2.0.\n",
                       "The unmodified corresponding source is available at the archive URL above.\n",
                       "MPL-2.0 text: https://www.mozilla.org/MPL/2.0/\n"]
    output += ["\nRust standard library: MIT OR Apache-2.0; corresponding source and toolchain notices:\n",
               "https://www.rust-lang.org/policies/licenses\n",
               "Statically linked musl libc: MIT; source and copyright/license text:\n",
               "https://musl.libc.org/ and https://git.musl-libc.org/cgit/musl/tree/COPYRIGHT\n"]
    return "".join(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "docs/third-party-notices.txt"
    text = generate()
    if args.check:
        if path.read_text() != text:
            raise SystemExit("license bundle is stale; run python3 scripts/generate-notices.py")
    else:
        path.write_text(text)
        print(f"wrote {path} ({len(text.encode())} bytes)")


if __name__ == "__main__":
    main()
